/**
 * Execute arbitrary SQL query and return results as JSON
 * For debugging and development only
 *
 * @param sql - SQL query to execute
 * @returns JSON string with query results
 *
 * @example
 * ```typescript
 * const result = executeSql("SELECT * FROM t_station WHERE name='東京'");
 * const data = JSON.parse(result);
 * console.log(data.rows);
 * ```
 */
export function executeSql(sql: string): string {
  return getModule().executeSql(sql);
}

/**
 * Type definition for SQL query result
 */
export interface SqlResult {
  columns: string[];
  rows: any[][];
  rowCount: number;
  error?: string;
}

/**
 * Type definition for database information
 */
export interface DatabaseInfo {
  result: boolean;
  dbName?: string;
  createdate?: string;
  reason?: string;
}

/**
 * Type definition for buildRoute result
 */
export interface BuildRouteResult {
  /** Result code (0 = success, negative = error) */
  rc: number;
  /** Failed item (station/line name that caused error) */
  failItem: string;
  /** Offset of word in route string where error occurred (0-based) */
  offset: number;
}
