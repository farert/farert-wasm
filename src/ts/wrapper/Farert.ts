/**
 * FARERT WASM Wrapper
 * TypeScript wrapper for WebAssembly module initialization
 */

import type { Farert as FaretClass } from '../types/farert';
import type { EmscriptenModule } from '../types/emscripten';

// Emscripten module interface
interface FaretModule extends EmscriptenModule {
  Farert: new () => FaretClass;
  openDatabase: () => string;
  closeDatabase: () => void;
  databaseInfo: () => string;

  // UI functions
  getPrefects: () => string;
  getCompanys: () => string;
  getLinesByPrefect: (prefecture: string) => string;
  getLinesByCompany: (company: string) => string;
  getLinesByStation: (station: string) => string;
  getStationsByCompanyAndLine: (jrgroup: string, lineName: string) => string;
  getStationsByPrefectureAndLine: (prefecture: string, lineName: string) => string;
  getPrefectureByStation: (stationName: string) => string;
  getKanaByStation: (stationName: string) => string;
  searchStationByKeyword: (keyword: string) => string;
  getBranchStationsByLine: (lineName: string, includeStationName: string) => string;
  getStationsByLine: (lineName: string) => string;
  getPrefectId: (prefecture: string) => number;
  getCompanyId: (company: string) => number;

  // Developer tools
  executeSql: (sql: string) => string;
}

let wasmModule: FaretModule | null = null;
let initPromise: Promise<FaretModule> | null = null;

/**
 * Initialize the FARERT WASM module
 * Must be called before using any FARERT functions
 */
export async function initFarert(): Promise<void> {
  if (wasmModule) {
    return; // Already initialized
  }

  if (initPromise) {
    await initPromise;
    return;
  }

  initPromise = (async () => {
    try {
      // Import the Emscripten-generated module
      // This will be generated by the build process
      // @ts-ignore - farert.js is generated by Emscripten build
      const createModule = await import('../farert.js').then(
        (m) => m.default || m
      );

      const module = await createModule({
        locateFile: (path: string, prefix: string) => {
          // WASM and data files are in dist/ directory
          // Use absolute URL to avoid path resolution issues
          if (path.endsWith('.wasm') || path.endsWith('.data')) {
            // Get the base URL from window.location
            const baseUrl = typeof window !== 'undefined'
              ? window.location.origin
              : '';
            return `${baseUrl}/dist/${path}`;
          }
          return prefix + path;
        }
      });
      wasmModule = module as FaretModule;

      // Auto-open database on initialization
      const dbStatus = wasmModule.openDatabase();
      console.log('[FARERT] Database initialized:', dbStatus);

      return wasmModule;
    } catch (error) {
      initPromise = null;
      throw new Error(`Failed to initialize FARERT WASM: ${error}`);
    }
  })();

  await initPromise;
}

/**
 * Get the initialized WASM module
 * @throws Error if module not initialized
 */
function getModule(): FaretModule {
  if (!wasmModule) {
    throw new Error(
      'FARERT WASM not initialized. Call initFarert() first.'
    );
  }
  return wasmModule;
}

/**
 * Farert class wrapper
 * Main interface for route calculation and fare information
 */
export class Farert {
  private instance: FaretClass;

  constructor() {
    const module = getModule();
    this.instance = new module.Farert();
  }

  // Route building methods
  addStartRoute(station: string): number {
    return this.instance.addStartRoute(station);
  }

  addRoute(line: string, station: string): number {
    return this.instance.addRoute(line, station);
  }

  autoRoute(useBulletTrain: number, destinationStation: string): number {
    return this.instance.autoRoute(useBulletTrain, destinationStation);
  }

  getRouteCount(): number {
    return this.instance.getRouteCount();
  }

  departureStationName(): string {
    return this.instance.departureStationName();
  }

  arrivevalStationName(): string {
    return this.instance.arrivevalStationName();
  }

  buildRoute(routeStr: string): string {
    return this.instance.buildRoute(routeStr);
  }

  routeScript(): string {
    return this.instance.routeScript();
  }

  // Route manipulation
  removeAll(): void {
    this.instance.removeAll();
  }

  removeTail(): void {
    this.instance.removeTail();
  }

  reverse(): number {
    return this.instance.reverse();
  }

  // Route configuration
  typeOfPassedLine(offset: number): number {
    return this.instance.typeOfPassedLine(offset);
  }

  setDetour(enabled: boolean): number {
    return this.instance.setDetour(enabled);
  }

  setNoRule(noRule: boolean): void {
    this.instance.setNoRule(noRule);
  }

  // Fare calculation
  showFare(): string {
    return this.instance.showFare();
  }

  // Route flags
  setLongRoute(flag: boolean): void {
    this.instance.setLongRoute(flag);
  }

  setJrTokaiStockApply(flag: boolean): void {
    this.instance.setJrTokaiStockApply(flag);
  }

  setStartAsCity(): void {
    this.instance.setStartAsCity();
  }

  setArrivalAsCity(): void {
    this.instance.setArrivalAsCity();
  }

  setSpecificTermRule115(flag: boolean): void {
    this.instance.setSpecificTermRule115(flag);
  }

  // Route status checks
  isNotSameKokuraHakataShinZai(): boolean {
    return this.instance.isNotSameKokuraHakataShinZai();
  }

  isAvailableReverse(): boolean {
    return this.instance.isAvailableReverse();
  }

  isOsakakanDetourEnable(): boolean {
    return this.instance.isOsakakanDetourEnable();
  }

  isOsakakanDetour(): boolean {
    return this.instance.isOsakakanDetour();
  }

  setNotSameKokuraHakataShinZai(enabled: boolean): void {
    this.instance.setNotSameKokuraHakataShinZai(enabled);
  }

  // JSON serialization
  getFareInfoObjectJson(): string {
    return this.instance.getFareInfoObjectJson();
  }

  getRoutesJson(): string {
    return this.instance.getRoutesJson();
  }

  getRouteRecord(index: number): string {
    return this.instance.getRouteRecord(index);
  }
}

